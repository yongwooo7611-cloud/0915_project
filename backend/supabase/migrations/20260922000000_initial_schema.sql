create or replace function public.sync_identity_sequences()
returns void language plpgsql security definer set search_path = '' as $$
begin
  perform setval(pg_get_serial_sequence('public.admins', 'id'), coalesce((select max(id) from public.admins), 1), exists(select 1 from public.admins));
  perform setval(pg_get_serial_sequence('public.users', 'id'), coalesce((select max(id) from public.users), 1), exists(select 1 from public.users));
  perform setval(pg_get_serial_sequence('public.posts', 'id'), coalesce((select max(id) from public.posts), 1), exists(select 1 from public.posts));
  perform setval(pg_get_serial_sequence('public.comments', 'id'), coalesce((select max(id) from public.comments), 1), exists(select 1 from public.comments));
end;
$$;
revoke all on function public.sync_identity_sequences() from public, anon, authenticated;
grant execute on function public.sync_identity_sequences() to service_role;
