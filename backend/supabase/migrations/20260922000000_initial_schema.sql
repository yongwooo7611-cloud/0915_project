create or replace view public.post_summaries
with (security_invoker = true) as
select p.id, p.user_id, p.category, p.title, p.content, p.view_count, p.is_hidden,
  p.created_at, p.updated_at, u.nickname as author, u.email as author_email,
  (select count(*) from public.comments c where c.post_id = p.id and not c.is_hidden) as comment_count,
  (select count(*) from public.post_reactions r where r.post_id = p.id and r.reaction = 'like') as like_count,
  (select count(*) from public.post_reactions r where r.post_id = p.id and r.reaction = 'dislike') as dislike_count
from public.posts p
join public.users u on u.id = p.user_id;

create or replace view public.comment_details
with (security_invoker = true) as
select c.id, c.post_id, c.user_id, c.content, c.is_hidden, c.created_at, c.updated_at,
  u.nickname as author, u.email as author_email, p.title as post_title
from public.comments c
join public.users u on u.id = c.user_id
join public.posts p on p.id = c.post_id;

create or replace function public.record_post_view(p_post_id bigint, p_user_id bigint)
returns integer language plpgsql security definer set search_path = '' as $$
declare
  inserted_count integer;
  current_views integer;
begin
  if not exists (select 1 from public.posts where id = p_post_id and not is_hidden) then
    raise exception 'POST_NOT_FOUND';
  end if;

  insert into public.post_views(post_id, user_id) values (p_post_id, p_user_id)
  on conflict do nothing;
  get diagnostics inserted_count = row_count;

  if inserted_count > 0 then
    update public.posts set view_count = view_count + 1 where id = p_post_id;
  end if;
  select view_count into current_views from public.posts where id = p_post_id;
  return current_views;
end;
$$;

create or replace function public.set_post_reaction(p_post_id bigint, p_user_id bigint, p_reaction text)
returns table(likes bigint, dislikes bigint)
language plpgsql security definer set search_path = '' as $$
begin
  if p_reaction is not null and p_reaction not in ('like', 'dislike') then
    raise exception 'INVALID_REACTION';
  end if;
  if not exists (select 1 from public.posts where id = p_post_id and not is_hidden) then
    raise exception 'POST_NOT_FOUND';
  end if;

  delete from public.post_reactions where post_id = p_post_id and user_id = p_user_id;
  if p_reaction is not null then
    insert into public.post_reactions(post_id, user_id, reaction)
    values (p_post_id, p_user_id, p_reaction);
  end if;

  return query select
    count(*) filter (where reaction = 'like'),
    count(*) filter (where reaction = 'dislike')
  from public.post_reactions where post_id = p_post_id;
end;
$$;

