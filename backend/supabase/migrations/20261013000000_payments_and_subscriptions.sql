begin;

create table public.payment_customers (
  user_id bigint primary key references public.users(id) on delete cascade,
  customer_key text not null unique,
  created_at timestamptz not null default now(),
  constraint payment_customers_key_length check (char_length(customer_key) between 2 and 50)
);

create table public.payment_orders (
  id uuid primary key default gen_random_uuid(),
  order_id text not null unique,
  user_id bigint not null references public.users(id) on delete cascade,
  kind text not null check (kind in ('credit', 'subscription')),
  product_id text not null,
  order_name text not null,
  amount integer not null check (amount > 0),
  credits integer not null default 0 check (credits >= 0),
  status text not null default 'pending' check (status in ('pending', 'completed', 'failed')),
  payment_key text unique,
  auth_key_hash text unique,
  method text,
  receipt_url text,
  toss_status text,
  failure_code text,
  approved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index payment_orders_user_created_idx on public.payment_orders(user_id, created_at desc);

create table public.credit_wallets (
  user_id bigint primary key references public.users(id) on delete cascade,
  balance integer not null default 0 check (balance >= 0),
  updated_at timestamptz not null default now()
);

create table public.credit_transactions (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  payment_order_id uuid unique references public.payment_orders(id) on delete restrict,
  amount integer not null check (amount <> 0),
  reason text not null,
  created_at timestamptz not null default now()
);

create index credit_transactions_user_created_idx on public.credit_transactions(user_id, created_at desc);

create table public.subscriptions (
  user_id bigint primary key references public.users(id) on delete cascade,
  plan_id text not null check (plan_id in ('sprout', 'forest')),
  status text not null check (status in ('active', 'canceled', 'past_due')),
  customer_key text not null unique,
  billing_key text,
  amount integer not null check (amount > 0),
  monthly_credits integer not null check (monthly_credits > 0),
  current_period_started_at timestamptz not null,
  current_period_ends_at timestamptz not null,
  last_payment_order_id uuid references public.payment_orders(id) on delete set null,
  canceled_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

drop trigger if exists payment_orders_set_updated_at on public.payment_orders;
create trigger payment_orders_set_updated_at before update on public.payment_orders
for each row execute function public.set_updated_at();

drop trigger if exists subscriptions_set_updated_at on public.subscriptions;
create trigger subscriptions_set_updated_at before update on public.subscriptions
for each row execute function public.set_updated_at();

alter table public.payment_customers enable row level security;
alter table public.payment_orders enable row level security;
alter table public.credit_wallets enable row level security;
alter table public.credit_transactions enable row level security;
alter table public.subscriptions enable row level security;

revoke all on table public.payment_customers, public.payment_orders, public.credit_wallets,
  public.credit_transactions, public.subscriptions from public, anon, authenticated;
grant all on table public.payment_customers, public.payment_orders, public.credit_wallets,
  public.credit_transactions, public.subscriptions to service_role;
grant usage, select on all sequences in schema public to service_role;

create or replace function public.finalize_credit_payment(
  p_order_id text,
  p_user_id bigint,
  p_payment_key text,
  p_toss_status text,
  p_method text,
  p_receipt_url text,
  p_approved_at timestamptz
)
returns table(balance integer, credited integer)
language plpgsql security definer set search_path = '' as $$
declare
  v_order public.payment_orders%rowtype;
  v_balance integer;
begin
  select * into v_order from public.payment_orders
  where order_id = p_order_id and user_id = p_user_id for update;
  if not found or v_order.kind <> 'credit' then raise exception 'payment order not found'; end if;

  if v_order.status = 'completed' then
    select coalesce(w.balance, 0) into v_balance from public.credit_wallets w where w.user_id = p_user_id;
    return query select coalesce(v_balance, 0), v_order.credits;
    return;
  end if;

  update public.payment_orders set status = 'completed', payment_key = p_payment_key,
    toss_status = p_toss_status, method = p_method, receipt_url = p_receipt_url,
    approved_at = p_approved_at, failure_code = null
  where id = v_order.id;

  insert into public.credit_wallets(user_id, balance) values (p_user_id, v_order.credits)
  on conflict (user_id) do update set balance = public.credit_wallets.balance + excluded.balance, updated_at = now()
  returning public.credit_wallets.balance into v_balance;

  insert into public.credit_transactions(user_id, payment_order_id, amount, reason)
  values (p_user_id, v_order.id, v_order.credits, 'credit_purchase');

  return query select v_balance, v_order.credits;
end;
$$;

create or replace function public.finalize_subscription_payment(
  p_order_id text,
  p_user_id bigint,
  p_payment_key text,
  p_customer_key text,
  p_billing_key text,
  p_toss_status text,
  p_method text,
  p_receipt_url text,
  p_approved_at timestamptz
)
returns table(balance integer, credited integer, period_ends_at timestamptz)
language plpgsql security definer set search_path = '' as $$
declare
  v_order public.payment_orders%rowtype;
  v_balance integer;
  v_period_end timestamptz;
begin
  select * into v_order from public.payment_orders
  where order_id = p_order_id and user_id = p_user_id for update;
  if not found or v_order.kind <> 'subscription' then raise exception 'subscription order not found'; end if;

  if v_order.status = 'completed' then
    select coalesce(w.balance, 0) into v_balance from public.credit_wallets w where w.user_id = p_user_id;
    select s.current_period_ends_at into v_period_end from public.subscriptions s where s.user_id = p_user_id;
    return query select coalesce(v_balance, 0), v_order.credits, v_period_end;
    return;
  end if;

  v_period_end := now() + interval '1 month';
  update public.payment_orders set status = 'completed', payment_key = p_payment_key,
    toss_status = p_toss_status, method = p_method, receipt_url = p_receipt_url,
    approved_at = p_approved_at, failure_code = null
  where id = v_order.id;

  insert into public.subscriptions(user_id, plan_id, status, customer_key, billing_key, amount,
    monthly_credits, current_period_started_at, current_period_ends_at, last_payment_order_id, canceled_at)
  values (p_user_id, v_order.product_id, 'active', p_customer_key, p_billing_key, v_order.amount,
    v_order.credits, now(), v_period_end, v_order.id, null)
  on conflict (user_id) do update set plan_id = excluded.plan_id, status = 'active',
    customer_key = excluded.customer_key, billing_key = excluded.billing_key, amount = excluded.amount,
    monthly_credits = excluded.monthly_credits, current_period_started_at = excluded.current_period_started_at,
    current_period_ends_at = excluded.current_period_ends_at, last_payment_order_id = excluded.last_payment_order_id,
    canceled_at = null;

  insert into public.credit_wallets(user_id, balance) values (p_user_id, v_order.credits)
  on conflict (user_id) do update set balance = public.credit_wallets.balance + excluded.balance, updated_at = now()
  returning public.credit_wallets.balance into v_balance;

  insert into public.credit_transactions(user_id, payment_order_id, amount, reason)
  values (p_user_id, v_order.id, v_order.credits, 'subscription_payment');

  return query select v_balance, v_order.credits, v_period_end;
end;
$$;

revoke all on function public.finalize_credit_payment(text, bigint, text, text, text, text, timestamptz) from public, anon, authenticated;
revoke all on function public.finalize_subscription_payment(text, bigint, text, text, text, text, text, text, timestamptz) from public, anon, authenticated;
grant execute on function public.finalize_credit_payment(text, bigint, text, text, text, text, timestamptz) to service_role;
grant execute on function public.finalize_subscription_payment(text, bigint, text, text, text, text, text, text, timestamptz) to service_role;

commit;
